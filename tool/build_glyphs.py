"""Bakes Roboto Flex hero glyphs into Dart outline data.

Each glyph is exported at point-compatible instances (a wdth x wght grid)
so the app can interpolate width and weight on its own, identically on iOS and web.

Run: uv run --with fonttools python -I tool/build_glyphs.py
"""

from __future__ import annotations

import sys
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tool/fonts/RobotoFlex.ttf"
OUT = ROOT / "lib/glyphs/glyph_data.g.dart"
LABEL_FONT = ROOT / "assets/fonts/RobotoFlexLabel.ttf"

CHARS = "0123456789+"
WDTH = (25.0, 75.0, 100.0, 151.0)
WGHT = (250.0, 600.0, 1000.0)
PINNED = {"opsz": 144.0, "YTFI": 788.0, "GRAD": 0.0, "slnt": 0.0}


def instance(wdth: float, wght: float) -> TTFont:
    font = TTFont(SOURCE)
    return instancer.instantiateVariableFont(font, {**PINNED, "wdth": wdth, "wght": wght})


def outline(font: TTFont, char: str):
    glyf = font["glyf"]
    name = font.getBestCmap()[ord(char)]
    glyph = glyf[name]
    coords, end_pts, flags = glyph.getCoordinates(glyf)
    advance = font["hmtx"][name][0]
    points = [c for xy in coords for c in xy]
    on_curve = [bool(f & 1) for f in flags]
    return points, list(end_pts), on_curve, advance


def dart_list(values) -> str:
    return "[" + ",".join(f"{v:g}" if isinstance(v, float) else str(v) for v in values) + "]"


def build_glyph_data() -> None:
    masters = [instance(w, g) for g in WGHT for w in WDTH]  # row-major: weight, then width
    lines = [
        "// GENERATED by tool/build_glyphs.py. Do not edit.",
        "// Roboto Flex (SIL Open Font License 1.1), see assets/licenses/RobotoFlex-OFL.txt",
        "",
        "part of 'glyph_set.dart';",
        "",
        f"const _upm = {masters[0]['head'].unitsPerEm}.0;",
        f"const _wdthStops = {dart_list(WDTH)};",
        f"const _wghtStops = {dart_list(WGHT)};",
        "",
    ]

    figure = []
    for font in masters:
        tops, bottoms = [], []
        for char in "0123456789":
            pts, *_ = outline(font, char)
            ys = pts[1::2]
            tops.append(max(ys))
            bottoms.append(min(ys))
        figure.append((max(tops), min(bottoms)))
    lines.append(f"const _figureTop = {dart_list([float(t) for t, _ in figure])};")
    lines.append(f"const _figureBottom = {dart_list([float(b) for _, b in figure])};")
    lines.append("")
    lines.append("const _glyphs = <String, _GlyphSource>{")

    for char in CHARS:
        shapes = [outline(font, char) for font in masters]
        if char == "+":
            # Sit the plus on the figures' optical center, not the math axis.
            centered = []
            for (points, end_pts, on_curve, advance), (top, bottom) in zip(shapes, figure):
                ys = points[1::2]
                shift = (top + bottom) / 2 - (max(ys) + min(ys)) / 2
                moved = [v + shift if i % 2 else v for i, v in enumerate(points)]
                centered.append((moved, end_pts, on_curve, advance))
            shapes = centered
        ref_end, ref_on = shapes[0][1], shapes[0][2]
        for _, end_pts, on_curve, _ in shapes[1:]:
            if end_pts != ref_end or on_curve != ref_on:
                sys.exit(f"Glyph {char!r} is not point-compatible across instances")
        key = char.replace("\\", "\\\\").replace("'", "\\'")
        lines.append(f"  '{key}': _GlyphSource(")
        lines.append(f"    ends: {dart_list(ref_end)},")
        lines.append(f"    onCurve: {dart_list(['true' if o else 'false' for o in ref_on])},")
        lines.append(f"    advances: {dart_list([float(s[3]) for s in shapes])},")
        lines.append("    masters: [")
        for points, *_ in shapes:
            lines.append(f"      {dart_list([float(p) for p in points])},")
        lines.append("    ],")
        lines.append("  ),")
    lines.append("};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


def build_label_font() -> None:
    from fontTools import subset

    font = TTFont(SOURCE)
    font = instancer.instantiateVariableFont(
        font,
        {
            "opsz": 14.0,
            "GRAD": 0.0,
            "slnt": 0.0,
            "wdth": 100.0,
            "XOPQ": 96.0,
            "YOPQ": 79.0,
            "XTRA": 468.0,
            "YTUC": 712.0,
            "YTLC": 514.0,
            "YTAS": 750.0,
            "YTDE": -203.0,
            "YTFI": 738.0,
        },
    )
    from io import BytesIO

    buffer = BytesIO()
    font.save(buffer)
    buffer.seek(0)
    font = TTFont(buffer)
    options = subset.Options()
    options.layout_features = ["kern", "tnum", "liga"]
    options.name_IDs = ["*"]
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=list(range(0x20, 0x7F)) + [0x00B7, 0x2192, 0x2212, 0x2013])
    subsetter.subset(font)
    LABEL_FONT.parent.mkdir(parents=True, exist_ok=True)
    font.save(LABEL_FONT)
    print(f"wrote {LABEL_FONT.relative_to(ROOT)} ({LABEL_FONT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    build_glyph_data()
    build_label_font()
